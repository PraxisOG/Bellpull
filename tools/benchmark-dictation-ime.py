#!/usr/bin/env python3
"""Compare the IME and composer on a disposable Android emulator with a virtual microphone.

Start stock-device-fixture.py on port 18646 and adb reverse that port. Install the
fixture APK, instrumentation and Moonshine Tiny. Grant microphone/notification
permissions, enable the fixture IME and enable the soft keyboard. Route the emulator
microphone to a PulseAudio null sink's monitor. Supply that sink and the directory
generated by prepare_speech_fixtures.py. JSON lines on stdout contain the results.
"""

import argparse
import base64
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import time


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--serial", required=True)
    parser.add_argument("--sink", required=True)
    parser.add_argument("--fixtures", type=Path, required=True)
    parser.add_argument("--passes", type=int, choices=(1, 2, 3), default=2)
    args = parser.parse_args()
    if not re.fullmatch(r"emulator-[0-9]+", args.serial):
        parser.error("Select an Android emulator serial.")

    root = Path(__file__).resolve().parents[1]
    manifest = json.loads((root / "benchmarks/speech/fixtures-manifest.json").read_text())
    fixtures = {row["id"]: row for row in manifest["fixtures"]}
    for row in fixtures.values():
        audio = args.fixtures / row["file"]
        if hashlib.sha256(audio.read_bytes()).hexdigest() != row["sha256"]:
            raise ValueError(f"Fixture digest mismatch for {audio}")
    references = json.dumps({name: row["reference"] for name, row in fixtures.items()}).encode()
    package = "org.praxisog.hermes.fixture"
    adb = ["adb", "-s", args.serial]
    command = adb + ["shell", "am", "instrument", "-w", "-r", "-e", "class",
                     "org.praxisog.hermes.DictationImeDeviceTest#comparesKeyboardAndComposerWithTheSameSpeech",
                     "-e", "dictationParity", "true", "-e", "parityPasses", str(args.passes),
                     "-e", "parityReferences", base64.b64encode(references).decode(),
                     package + ".test/androidx.test.runner.AndroidJUnitRunner"]
    passed = False
    expected = {f"{lap}/{name}/{route}" for lap in range(args.passes)
                for name in fixtures for route in ("ime", "app")}
    received = set()
    with subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True) as process:
        for line in process.stdout:
            print(line.rstrip(), file=sys.stderr, flush=True)
            if line.startswith("INSTRUMENTATION_STATUS: play_clip="):
                request = line.strip().split("=", 1)[1]
                if request not in expected or request in received:
                    raise ValueError(f"Unexpected playback request {request}")
                name = request.split("/")[1]
                time.sleep(1.5)  # Allow the virtual microphone stream to settle.
                subprocess.run(["paplay", "--device", args.sink, str(args.fixtures / fixtures[name]["file"])], check=True)
                subprocess.run(adb + ["shell", "run-as", package, "touch", "files/parity-playback-done"], check=True)
            if line.startswith("INSTRUMENTATION_STATUS: parity_sample="):
                row = json.loads(line.split("=", 1)[1])
                if row["request"] not in expected or row["request"] in received:
                    raise ValueError("Invalid or duplicate result")
                received.add(row["request"])
                print(json.dumps(row), flush=True)
            if "OK (1 test)" in line:
                passed = True
        if process.wait() or not passed or received != expected:
            raise SystemExit("Dictation comparison did not complete")


if __name__ == "__main__":
    main()
